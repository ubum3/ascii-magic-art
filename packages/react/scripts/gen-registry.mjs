#!/usr/bin/env node
/*
 * gen-registry.mjs: reads every piece's meta from the installed ascii-magic-art
 * and writes src/registry/*.generated.ts:
 *   loaders  slug -> () => import("ascii-magic-art/pieces/<slug>.js"), one lazy chunk each
 *   sizes    slug -> [cols, rows, square], so a player can hold its space before the piece loads
 *   catalog  name, category, note and tags, for gallery pages
 * The import() calls are written out one by one: bundlers split plain string imports
 * reliably, template strings much less so.
 */
import fs from "fs";
import path from "path";
import { createRequire } from "module";
import { fileURLToPath, pathToFileURL } from "url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, "..", "src", "registry");
const require = createRequire(import.meta.url);
const ROOT = path.dirname(require.resolve("ascii-magic-art/package.json"));
const DIR = path.join(ROOT, "pieces");

const slugs = fs.readdirSync(DIR).filter((f) => f.endsWith(".js")).map((f) => f.slice(0, -3)).sort();
const metas = [];
for (const slug of slugs) metas.push((await import(pathToFileURL(path.join(DIR, slug + ".js")).href)).meta);
const cats = JSON.parse(fs.readFileSync(path.join(ROOT, "categories.json"), "utf8"));

const HEAD = "// Generated by scripts/gen-registry.mjs from ascii-magic-art. Do not edit; run `npm run gen`.\n";
const q = JSON.stringify;

const sizes = HEAD + `
/** [cols, rows, square cells (1) or text cells (0)] for every piece. */
export const SIZES = {
${metas.map((m) => `  ${q(m.slug)}: [${m.cols}, ${m.rows}, ${m.cell === "square" ? 1 : 0}],`).join("\n")}
} as const;

/** The name of any piece in the library. */
export type PieceSlug = keyof typeof SIZES;
`;

const loaders = HEAD + `import type { PieceModule } from "ascii-magic-art/lib/types.js";
import type { PieceSlug } from "./sizes.generated.js";

export const LOADERS: Record<PieceSlug, () => Promise<PieceModule>> = {
${slugs.map((s) => `  ${q(s)}: () => import("ascii-magic-art/pieces/${s}.js"),`).join("\n")}
};
`;

const catalog = HEAD + `import type { PieceSlug } from "./sizes.generated.js";

export interface CatalogEntry {
  slug: PieceSlug; name: string; category: string; note: string; tags: readonly string[];
  cols: number; rows: number; fps: number; square: boolean;
}
export interface Category { id: string; name: string; blurb: string }

export const CATEGORIES: readonly Category[] = ${q(cats.map(({ id, name, blurb }) => ({ id, name, blurb })), null, 2)};

export const CATALOG: readonly CatalogEntry[] = [
${metas.map((m) => `  ${q({ slug: m.slug, name: m.name, category: m.category, note: m.note, tags: m.tags, cols: m.cols, rows: m.rows, fps: m.fps, square: m.cell === "square" })},`).join("\n")}
];
`;

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, "sizes.generated.ts"), sizes);
fs.writeFileSync(path.join(OUT, "loaders.generated.ts"), loaders);
fs.writeFileSync(path.join(OUT, "catalog.generated.ts"), catalog);
console.log(`registry: ${slugs.length} pieces from ${path.relative(process.cwd(), ROOT) || "."}`);
