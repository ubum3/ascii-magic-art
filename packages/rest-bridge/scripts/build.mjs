#!/usr/bin/env node
/*
 * build.mjs: dist/, for everything that can't run ascii.rest's TypeScript as is
 * (browsers, bundlers, Node before 22.18, files under node_modules). esbuild
 * strips the types; with splitting, each of their pieces stays its own chunk,
 * loaded only when asked for. ascii-magic-art itself stays external.
 */
import * as esbuild from "esbuild";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const HERE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.resolve(HERE, "../../ascii/src/library.ts");
if (!fs.existsSync(SRC)) {
  // Installed from a tarball, dist/ already came with it.
  if (fs.existsSync(path.join(HERE, "dist/index.js"))) process.exit(0);
  console.error(`ascii-magic-art-rest: no ascii.rest checkout at ${path.dirname(path.dirname(SRC))}`);
  console.error("  git clone https://github.com/bas3line/ascii ascii   (in the repo root)");
  process.exit(1);
}
// src/catalog.js: every piece's name, size and tags, so a page can lay out a
// piece's box (or a search can find it) without loading the piece.
const rest = await import(path.join(HERE, "src/index.js"));
const rows = [];
for (const name of rest.restNames) {
  const { meta: m } = rest.fromRest(await rest.restModule(name), { slug: "rest-" + name });
  rows.push([m.slug, m.name, m.category, m.tags[1], m.note, m.cols, m.rows, m.fps, m.cell === "square" ? 1 : 0]);
}
const catalog = `// Generated by scripts/build.mjs from ascii.rest's pieces. Do not edit.
/** [slug, name, category (ours), category (theirs), note, cols, rows, fps, square] for every ascii.rest piece. */
export const REST_CATALOG = ${JSON.stringify(rows).replace(/\],\[/g, "],\n  [").replace(/^\[\[/, "[\n  [").replace(/\]\]$/, "],\n]")};
`;
if (!fs.existsSync(path.join(HERE, "src/catalog.js")) || fs.readFileSync(path.join(HERE, "src/catalog.js"), "utf8") !== catalog) {
  fs.writeFileSync(path.join(HERE, "src/catalog.js"), catalog);
  console.log("ascii-magic-art-rest: src/catalog.js updated");
}
fs.rmSync(path.join(HERE, "dist"), { recursive: true, force: true });
const r = await esbuild.build({
  entryPoints: { index: path.join(HERE, "src/index.js") },
  outdir: path.join(HERE, "dist"),
  bundle: true, splitting: true, format: "esm", platform: "neutral", target: "es2020",
  chunkNames: "chunks/[name]-[hash]", minifyWhitespace: true, minifySyntax: true,
  external: ["ascii-magic-art", "ascii-magic-art/*"],
  banner: { js: "// ascii.rest by bas3line (https://github.com/bas3line/ascii), MIT licensed. Bundled by ascii-magic-art-rest." },
  metafile: true, logLevel: "warning",
});
const bytes = Object.values(r.metafile.outputs).reduce((s, o) => s + o.bytes, 0);
console.log(`ascii-magic-art-rest: dist/ ${Object.keys(r.metafile.outputs).length} files, ${(bytes / 1024).toFixed(0)} KB`);
